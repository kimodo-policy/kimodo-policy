#!/usr/bin/env bash
# Robot-side software installation only. Never starts hardware services.
set -Eeuo pipefail
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
CONDA_BIN="${CONDA_EXE:-}"
DRY_RUN=0 CHECK_ONLY=0 SYSTEM_DEPS=0 DOWNLOAD=0
ARCHIVE=""
die() { printf '[workstation] ERROR: %s\n' "$*" >&2; exit 1; }
value() { [[ $# -ge 2 && -n "$2" && "$2" != --* ]] || die "$1 requires a value"; }
while (( $# )); do
  case "$1" in
    --only) value "$@"; [[ "$2" == workstation ]] || die 'Use --only workstation'; shift 2 ;;
    --conda) value "$@"; CONDA_BIN="$2"; shift 2 ;;
    --runtime-archive) value "$@"; ARCHIVE="$2"; shift 2 ;;
    --dry-run) DRY_RUN=1; shift ;;
    --check) CHECK_ONLY=1; shift ;;
    --system-deps) SYSTEM_DEPS=1; shift ;;
    --download-resources) DOWNLOAD=1; shift ;;
    *) die "Unknown workstation option: $1" ;;
  esac
done
(( DRY_RUN + CHECK_ONLY <= 1 )) || die '--dry-run and --check are mutually exclusive'
(( ! CHECK_ONLY || !(SYSTEM_DEPS || DOWNLOAD) )) || die '--check does not install/download'
printf '%s\n' '[workstation] Plan:' \
  '  Create isolated Python 3.10 teleoperation and collection environments.' \
  '  Install pinned dependencies, CPU PyTorch and pinned LeRobot sources.' \
  '  Verify/extract the workstation runtime and apply the collection overlay.' \
  '  Build SONIC and check imports, GMR mappings and dynamic libraries.' \
  '  Save paths under real-world/.state/; keep local.env overrides.' \
  '  Robot/PICO/camera services are not started.'
(( ! DRY_RUN )) || exit 0
[[ "$(uname -s)" == Linux && "$(uname -m)" == x86_64 ]] || die 'Requires Linux x86_64.'
unset PYTHONHOME PYTHONPATH VIRTUAL_ENV
export PYTHONNOUSERSITE=1 GIT_LFS_SKIP_SMUDGE=1
if [[ -z "$CONDA_BIN" ]]; then CONDA_BIN="$(type -P conda || true)"; fi
if [[ -z "$CONDA_BIN" ]]; then
  for c in "$HOME/miniconda3/bin/conda" "$HOME/anaconda3/bin/conda" "$HOME/miniforge3/bin/conda"; do
    if [[ -x "$c" ]]; then CONDA_BIN="$c"; break; fi
  done
fi
[[ -x "$CONDA_BIN" ]] || die 'Install Conda or provide --conda /path/to/bin/conda.'
CONDA_BASE="$("$CONDA_BIN" info --base)"
BOOTSTRAP_PYTHON="$CONDA_BASE/bin/python"
command -v nvidia-smi >/dev/null && nvidia-smi -L >/dev/null || die 'A working NVIDIA GPU/driver is required by SONIC.'
if (( CHECK_ONLY )); then
  [[ -f "$ROOT/.state/workstation.env" ]] || die 'Workstation setup has not completed in this checkout.'
  source "$ROOT/env.sh"
  "$TELEOP_PYTHON" "$ROOT/tools/check_environment.py" teleop
  "$COLLECTION_PYTHON" "$ROOT/tools/check_environment.py" collection
  bash "$ROOT/collection/bin/check-local"
  exit 0
fi
mkdir -p "$ROOT/.state"
LOG="$ROOT/.state/workstation-$(date +%Y%m%d-%H%M%S)-$$.log"
exec > >(tee -a "$LOG") 2>&1
trap 'rc=$?; printf "[workstation] Failed at line %s; see %s\n" "$LINENO" "$LOG" >&2; exit "$rc"' ERR
if (( SYSTEM_DEPS )); then
  command -v apt-get >/dev/null || die '--system-deps requires Ubuntu/Debian apt-get.'
  SUDO=(); (( EUID == 0 )) || SUDO=(sudo)
  "${SUDO[@]}" apt-get update
  "${SUDO[@]}" apt-get install -y build-essential pkg-config libeigen3-dev libgtest-dev \
    libzmq3-dev zlib1g-dev libyaml-cpp-dev libusb-1.0-0 libgl1 libglib2.0-0 \
    libmpfr6 libmpc3 libgmp10 rsync git git-lfs ffmpeg espeak
fi
for c in git make pkg-config; do command -v "$c" >/dev/null || die "Missing $c; use --system-deps."; done
RESOURCE_ARGS=(--root "$ROOT")
if [[ -n "$ARCHIVE" ]]; then RESOURCE_ARGS+=(--archive "$ARCHIVE"); fi
(( ! DOWNLOAD )) || RESOURCE_ARGS+=(--download)
"$BOOTSTRAP_PYTHON" "$ROOT/tools/prepare_workstation.py" "${RESOURCE_ARGS[@]}"
for role in teleop collection; do
  prefix="$ROOT/.envs/kimodo-$role"
  if [[ ! -e "$prefix" ]]; then
    "$CONDA_BIN" create -y --prefix "$prefix" python=3.10 pip
  fi
  [[ -x "$prefix/bin/python" ]] || die "Invalid existing environment: $prefix"
  "$prefix/bin/python" -c 'import sys; assert sys.version_info[:2] == (3,10), "Python 3.10 required"'
  "$prefix/bin/python" -m pip install --upgrade pip
  "$prefix/bin/python" -m pip install torch==2.6.0+cpu torchvision==0.21.0+cpu \
    --index-url https://download.pytorch.org/whl/cpu
  "$prefix/bin/python" -m pip install -r "$ROOT/environments/$role.requirements.txt"
done
export KIMODO_WORKSTATION_INSTALLING=1
source "$ROOT/env.sh"
# Install only into this checkout's managed environments.
export TELEOP_PYTHON="$ROOT/.envs/kimodo-teleop/bin/python"
export COLLECTION_PYTHON="$ROOT/.envs/kimodo-collection/bin/python"
export WBC_ROOT="$ROOT/external/GR00T-WholeBodyControl" GMR_ROOT="$ROOT/external/GMR"
export COLLECTION_ROOT="$ROOT/runtime" SONIC_NATIVE_ROOT="$ROOT/runtime/native"
export KIMODO_COLLECTION_ROOT="$COLLECTION_ROOT"
bash "$ROOT/setup/install_python_sources.sh"
bash "$ROOT/collection/bin/build-sonic"
bash "$ROOT/collection/bin/check-local"
{
  echo '# Generated by setup.sh --only workstation. local.env overrides these paths.'
  for key in TELEOP_PYTHON COLLECTION_PYTHON WBC_ROOT GMR_ROOT COLLECTION_ROOT SONIC_NATIVE_ROOT; do
    printf 'export %s=%q\n' "$key" "${!key}"
  done
} > "$ROOT/.state/workstation.env.tmp"
mv "$ROOT/.state/workstation.env.tmp" "$ROOT/.state/workstation.env"
if [[ ! -f "$ROOT/deploy/deploy_config.json" ]]; then cp "$ROOT/deploy/deploy_config.example.json" "$ROOT/deploy/deploy_config.json"; fi
printf '%s\n' '[workstation] Installation and local software checks passed.' \
  'Next: configure robot/PICO/camera/server settings in real-world/local.env, then source real-world/env.sh.' \
  'Physical device checks and pose calibration are separate steps in the real-world guide.'
